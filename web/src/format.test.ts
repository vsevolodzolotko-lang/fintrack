import { describe, expect, it } from "vitest";
import { dayLabel, fmtDate, ymdKyiv } from "./format";

// vitest.config.ts форсує TZ=America/New_York для всього web-сьюту — це той
// самий трюк, що ловить "рахує в браузерному поясі" баги в ymdKyiv/dayLabel.
// fmtDate мусить показувати київський час незалежно від пояса браузера.
describe("fmtDate", () => {
  it("показує київський час, а не браузерний", () => {
    // 23:05 UTC 31 липня — це вже 02:05 1 серпня в Києві (UTC+3), і 19:05
    // за Нью-Йорком (UTC-4) того ж 31 липня. Формат мусить показати київську
    // дату/час, не нью-йоркську.
    expect(fmtDate("2026-07-31T23:05:00.000Z")).toBe("01 серп., 02:05");
  });
});

describe("ymdKyiv", () => {
  it("дає київський день, а не UTC", () => {
    // 22:30 UTC 30 липня — це вже 01:30 31 липня в Києві (UTC+3).
    expect(ymdKyiv("2026-07-30T22:30:00.000Z")).toBe("2026-07-31");
  });

  it("не зсуває день у межах доби", () => {
    expect(ymdKyiv("2026-07-31T09:00:00.000Z")).toBe("2026-07-31");
  });

  it("правильно працює на межі місяця", () => {
    expect(ymdKyiv("2026-07-31T21:10:00.000Z")).toBe("2026-08-01");
  });
});

describe("dayLabel", () => {
  it("сьогодні і вчора — словами", () => {
    expect(dayLabel("2026-07-31", "2026-07-31")).toBe("Сьогодні");
    expect(dayLabel("2026-07-30", "2026-07-31")).toBe("Вчора");
  });

  it("раніше — числом і місяцем", () => {
    expect(dayLabel("2026-07-12", "2026-07-31")).toBe("12 лип");
  });

  it("вчора через межу місяця", () => {
    expect(dayLabel("2026-07-31", "2026-08-01")).toBe("Вчора");
  });
});
