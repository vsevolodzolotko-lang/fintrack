import { describe, expect, it } from "vitest";
import { originCaption } from "./closedGoals";

// Суми навмисне до 1000 — тоді Intl не вставляє розділювач груп (nbsp), і
// рядок можна порівнювати дослівно, не воюючи з невидимим символом.
describe("originCaption", () => {
  it("нічого не відкладали → не з відкладеного", () => {
    // Кейс, з якого все почалось: iphone на ₴0 / ₴18 000, куплений із вільного.
    expect(originCaption(500_00n, 0n)).toBe("не з відкладеного");
  });

  it("нуль відкладеного важливіший за додатну delta", () => {
    // Інакше галузка delta > 0 дала б «₴0 відкладено + ₴500 з вільного» —
    // формально правду, яку неприємно читати.
    expect(originCaption(500_00n, 0n)).not.toContain("+");
  });

  it("доплатили з вільного", () => {
    expect(originCaption(700_00n, 500_00n)).toBe("₴500 відкладено + ₴200 з вільного");
  });

  it("зекономили — залишок повернувся", () => {
    expect(originCaption(300_00n, 500_00n)).toBe("₴500 відкладено, ₴200 повернулось");
  });

  it("рівно з відкладеного", () => {
    expect(originCaption(500_00n, 500_00n)).toBe("рівно з відкладеного");
  });

  it("приймає копійки рядком, як їх віддає API", () => {
    expect(originCaption("70000", "50000")).toBe("₴500 відкладено + ₴200 з вільного");
  });
});
