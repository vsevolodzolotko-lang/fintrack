import { describe, expect, it } from "vitest";
import { pressKey, pressPrefilled } from "./amountKeys";

/** Набрати послідовність клавіш з порожнього поля. */
function type(keys: string[], decimals: boolean): string {
  return keys.reduce((v, k) => pressKey(v, k, decimals), "");
}

describe("pressKey — цілі гривні (decimals: false)", () => {
  it("дописує цифри", () => {
    expect(type(["1", "2", "3"], false)).toBe("123");
  });

  it("«000» дописує три нулі", () => {
    expect(type(["5", "000"], false)).toBe("5000");
  });

  it("«000» на порожньому полі нічого не робить", () => {
    // Інакше «000» саме по собі читалося б як нуль, а це не сума.
    expect(type(["000"], false)).toBe("");
  });

  it("кома ігнорується — тут копійок не буває", () => {
    expect(type(["1", ",", "5"], false)).toBe("15");
  });

  it("провідний нуль не накопичується", () => {
    expect(type(["0", "5"], false)).toBe("5");
  });

  it("«⌫» знімає останній символ", () => {
    expect(type(["1", "2", "⌫"], false)).toBe("1");
  });

  it("«⌫» на порожньому полі безпечне", () => {
    expect(pressKey("", "⌫", false)).toBe("");
  });

  it("довжина обмежена сімома символами", () => {
    expect(type(["1", "2", "3", "4", "5", "6", "7", "8"], false)).toBe("1234567");
  });
});

describe("pressKey — з копійками (decimals: true)", () => {
  it("кома дозволена один раз", () => {
    expect(type(["1", "2", ",", "3", ",", "4"], true)).toBe("12,34");
  });

  it("кома на порожньому полі нічого не робить", () => {
    // «,5» не сума; хай спершу буде ціла частина.
    expect(type([","], true)).toBe("");
  });

  it("після коми не більше двох знаків", () => {
    expect(type(["1", ",", "2", "3", "4"], true)).toBe("1,23");
  });

  it("«000» ігнорується — його місце займає кома", () => {
    expect(type(["5", "000"], true)).toBe("5");
  });

  it("«⌫» знімає кому так само, як цифру", () => {
    expect(type(["1", ",", "⌫"], true)).toBe("1");
  });

  it("провідний нуль не накопичується, але «0,» дозволений", () => {
    expect(type(["0", ",", "5"], true)).toBe("0,5");
    expect(type(["0", "5"], true)).toBe("5");
  });
});

/** Набрати послідовність клавіш поверх незайманого префілу. */
function typeOver(prefill: string, keys: string[], decimals: boolean): string {
  let st = { value: prefill, pristine: true };
  for (const k of keys) st = pressPrefilled(st.value, k, decimals, st.pristine);
  return st.value;
}

describe("pressPrefilled — префіл як підказка", () => {
  // Той самий баг, що замикав шит «Куплено» на цілі з нульовим балансом:
  // «0,00» — це вже дві цифри після коми, тож pressKey глушив кожну цифру,
  // і суму покупки не було як увести взагалі.
  it("цифра поверх «0,00» починає суму з нуля, а не глухне", () => {
    expect(typeOver("0,00", ["1", "8", "0", "0", "0"], true)).toBe("18000");
  });

  it("цифра поверх будь-якого префілу з копійками замінює його", () => {
    expect(typeOver("1037,71", ["5", "0"], true)).toBe("50");
  });

  it("«⌫» правит префіл, а не стирає його весь", () => {
    expect(typeOver("12,34", ["⌫"], true)).toBe("12,3");
  });

  it("після першої клавіші префіл уже не незайманий — цифри дописуються", () => {
    expect(typeOver("0,00", ["1", "2"], true)).toBe("12");
    expect(typeOver("12,34", ["⌫", "9"], true)).toBe("12,39");
  });

  it("кома поверх префілу з комою нічого не ламає", () => {
    expect(typeOver("12,34", [",", "⌫"], true)).toBe("12,3");
  });

  it("«000» поверх префілу дописує нулі — це множник, не нова сума", () => {
    expect(typeOver("18", ["000"], false)).toBe("18000");
  });

  it("порожній префіл поводиться як звичайний набір", () => {
    expect(typeOver("", ["1", "2", "3"], false)).toBe("123");
  });
});
